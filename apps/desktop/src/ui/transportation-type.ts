export function normalizeTransportationTypeKey(
  value: string | null | undefined,
): TransportationTypeKey | null {
  if (value == null || value === "") return null;
  return (TRANSPORTATION_TYPE_KEYS as readonly string[]).includes(value)
    ? (value as TransportationTypeKey)
    : null;
}

export function transportationTypeLabelZh(
  value: string | null | undefined,
): string | null {
  const key = normalizeTransportationTypeKey(value);
  return key ? TRANSPORTATION_TYPE_LABEL_ZH[key] : null;
}

export function transportationTypeIconSvg(
  value: string | null | undefined,
  options?: { size?: number; flightGlyph?: FlightTransportationGlyph },
): string {
  const size = options?.size ?? 16;
  const key = normalizeTransportationTypeKey(value);
  if (!key) return lucide(ICON_PATHS.null, size);
  if (key === "flight" && options?.flightGlyph === "arrival") {
    return lucide(FLIGHT_ARRIVAL_PATHS, size);
  }
  return lucide(ICON_PATHS[key], size);
}
